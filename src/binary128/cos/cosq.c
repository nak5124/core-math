/* This file is sinq.c with the entry point switched to the cosine: keep
   the two in sync.

   This is a C port of the binary128 sine/cosine of metallic-rs
   (https://github.com/jdh8/metallic-rs, src/f128_/trig.rs), extended from
   round-to-nearest to the four IEEE rounding modes. AI agents assisted with
   the port and subsequent revisions. Methodology and related agent skills:
   https://jdh8.org/how-to-program-math-functions/
   https://github.com/jdh8/metallic-rs/blob/main/.claude/skills/program-math-functions/SKILL.md
   https://github.com/jdh8/metallic/blob/main/.claude/skills/program-math-functions/SKILL.md
   Review: https://gitlab.inria.fr/core-math/core-math/-/work_items/47
   Fast-path error argument: ../sin/sinq_error.md.

   The sine is odd and the
   cosine even, so both run one pipeline on |x| in unsigned fixed point:

   1. Reduce.  x*2/pi is formed as the exact product of the 113-bit
      significand with a window of 2/pi cut from 64-bit limbs at the exponent
      (Payne-Hanek): six limbs on the fast path, ten on the accurate one.
      Bits of 2/pi above the window contribute multiples of 4 to x*2/pi and
      drop, bits below it stay under the last bit kept; what is left is the
      quadrant and a fraction, 192 bits wide on the fast path and 448 on the
      accurate one.
   2. Split.  Quadrant and fraction round to n = round(256*x/pi) mod 512: the
      quadrant n>>7 and a breakpoint j = n & 127, leaving a signed residual g
      with |g| <= 1/256, so theta = g*pi/2 stays below pi/512 < 2^-7.34.  |g|
      is normalized into a floating fraction at its own exponent, so the
      residual keeps full relative precision however deep the cancellation;
      the fast path only insists on 136 of its 192 bits (MAX_LZ) and hands
      anything closer to a multiple of pi/2 over.  No binary128 comes within
      2^-124 of a multiple of pi/2 (sin.sage), so the 448-bit residual keeps
      over 300 bits.
   3. Evaluate.  sin(theta) = theta*(1 - u*(A - u*B)) and 1 - cos(theta) =
      u*(1/2 - u*(E - u*O)) for u = theta^2, with A, B, E, O the even and odd
      halves of polynomials in v = u^2: a degree-four minimax for sine and
      six Taylor terms for cosine at the fast width, eighteen Taylor
      coefficients each at the accurate width, summed in three tiers (128,
      256 and 384 bits) since the high-order terms ride powers of u that
      bury a narrower width's slack; the sums are within 2^-296 of exact.
   4. Recombine.  With A = j*pi/256 + theta, sin|x| is +-sin A or +-cos A by
      quadrant, and sin A = S_j*cos(theta) + C_j*sin(theta), cos A =
      C_j*cos(theta) - S_j*sin(theta) from tables of sin(j*pi/256) and
      cos(j*pi/256), in a frame at 2^-256 (fast) or 2^-384 (accurate).  j = 0
      with the sine wanted keeps the floating form of sin(theta) all the way.
   5. Round.  The fast path keeps a 15-bit guard below the 113-bit
      significand; its error is below ZIV_GATE units of that guard
      (see ../sin/sinq_error.md and sinq_tables.py), so it decides
      whenever the guard is farther than the gate from the rounding boundary:
      the midpoint for round-to-nearest, the grid point for directed modes.
      Everything else goes to the 384-bit path, which rounds outright.

   Below |x| = 2^-8 (DIRECT) there is nothing to reduce: theta = x exactly.
   Below 2^-57 (TINY) the cubic and quadratic terms sit under half an ulp, so
   sin(x) = x and cos(x) = 1 in round-to-nearest, and one ulp toward zero in
   the directed modes that round toward zero.

   Constants (limbs of 2/pi and pi/2, table values, Taylor terms) and the
   independent minimax SIN_FAST are generated by ../sin/sinq_tables.py;
   regenerate rather than edit. */

