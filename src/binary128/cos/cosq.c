/* Rounding mode and exception flags.  On x86-64 read MXCSR once, accumulate
   the flags and write it back only when something changed, as the other
   binary128 functions do; elsewhere fall back to fenv.h. */
#ifdef __x86_64__
#define RM_NEAREST _MM_ROUND_NEAREST
#define RM_UP _MM_ROUND_UP
#define RM_DOWN _MM_ROUND_DOWN
#define FENV_GET(rm, flags) do { flags = _mm_getcsr(); rm = flags & _MM_ROUND_MASK; } while (0)
#define FENV_RAISE(oflags, flags) do { if (__builtin_expect(oflags != flags, 0)) _mm_setcsr(flags); } while (0)
#else
#define RM_NEAREST FE_TONEAREST
#define RM_UP FE_UPWARD
#define RM_DOWN FE_DOWNWARD
#define FENV_GET(rm, flags) do { flags = 0; rm = fegetround(); } while (0)
#define FENV_RAISE(oflags, flags) do { if (__builtin_expect(oflags != flags, 0)) feraiseexcept(flags); } while (0)
#endif

// In a directed mode, whether the result of this sign rounds away from zero.
static inline int round_away(unsigned rm, u128 sign) {
  return sign ? rm == RM_DOWN : rm == RM_UP;
}

#define SIGN_MASK ((u128)1 << 127)
#define EXP_MASK ((u128)0x7fff << 112)
#define MANTISSA_MASK (((u128)1 << 112) - 1)
#define IMPLICIT_BIT ((u128)1 << 112)
#define QUIET_BIT ((u128)1 << 111)
#define BIAS 0x3fff
#define ONE ((u128)BIAS << 112)

/* Below 2^-57 the sine rounds to x and the cosine to 1: x^3/6 < 2^-173.5 sits
   under the half ulp 2^-171 of x, and x^2/2 < 2^-115 under the half ulp
   2^-114 below 1. */
#define TINY ((u128)(BIAS - 57) << 112)

// Below 2^-8 the argument is its own reduced angle: no window, no table.
#define DIRECT (-8)

/* Leading zeros of the fast path's 192-bit residual past which it gives up:
   136 bits are left at the limit, against a relative need of about 130. */
#define MAX_LZ 56

// Discarded bits below the fast path's 113-bit significand within its top limb.
#define GUARD 15
#define GUARD_MASK ((1u << GUARD) - 1)
#define GUARD_HALF (1u << (GUARD - 1))

/* Half-width of the window around a rounding boundary the fast path refuses
   to decide, in units of 2^(e2-128), or 2^-15 ulp in the returned frame.
   The analytic bound is < 15.8 units, including reduction, evaluation and
   recombination; see ../sin/sinq_error.md. This covers midpoint boundaries
   in round-to-nearest and grid boundaries in directed modes. Sampled MPFR
   error measurements are additional checks, not a proof of the bound. */
#define ZIV_GATE 16u

static inline __float128 asf128(u128 t) {
#if defined(__SSE4_1__) && !defined(__clang__)
  // put u128 into xmm register
  __m128i m = {0, 0};
  m = _mm_insert_epi64 (m, t, 0);
  m = _mm_insert_epi64 (m, t>>64, 1);
  __float128 r;
  asm("": "=x"(r): "0"(m));
  return r;
#else
  b128u128_u u = {.a = t};
  return u.f;
#endif
}

static inline u128 asu128(__float128 z) {
#if defined(__SSE4_1__) && !defined(__clang__)
  __m128i t;
  asm("" : "=x" (t) :"0" (z));
  u64 h = _mm_extract_epi64(t, 1);
  u64 l = _mm_extract_epi64(t, 0);
  return ((u128)h<<64)|l;
#else
  b128u128_u u = {.f = z};
  return u.a;
#endif
}

