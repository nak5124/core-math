/* ---------- wide unsigned arithmetic ---------- */

// leading zeros of a 128-bit value, 128 when it is zero
static inline int clz128(u128 x) {
  u64 h = x >> 64, l = x;
  if (h) return __builtin_clzll(h);
  return l ? 64 + __builtin_clzll(l) : 128;
}

// the low 64 bits of (high:low) >> shift, for shift < 64
static inline u64 funnel_down(u64 low, u64 high, unsigned shift) {
  return (low >> shift) | (high << 1 << (63 - shift));
}

// full 128x128-bit product
static inline void wmul(u128 x, u128 y, u128 *high, u128 *low) {
  u64 xl = x, xh = x >> 64, yl = y, yh = y >> 64;
  u128 ll = (u128)xl * yl, lh = (u128)xl * yh, hl = (u128)xh * yl, hh = (u128)xh * yh;
  u128 mid = (ll >> 64) + (u64)lh + (u64)hl;
  *low = (mid << 64) | (u64)ll;
  *high = hh + (lh >> 64) + (hl >> 64) + (mid >> 64);
}

/* approximate high half of a 128x128-bit product from three 64-bit products:
   up to two units short of the exact high half, never over */
static inline u128 mhi_approx(u128 x, u128 y) {
  u128 xh = x >> 64, xl = (u64)x, yh = y >> 64, yl = (u64)y;
  return xh * yh + ((xh * yl) >> 64) + ((xl * yh) >> 64);
}

static inline u256 add_256(u256 a, u256 b) {
  u256 r;
  int c = __builtin_add_overflow(a.l[0], b.l[0], &r.l[0]);
  r.l[1] = a.l[1] + b.l[1] + c;
  return r;
}

static inline u256 sub_256(u256 a, u256 b) {
  u256 r;
  int c = __builtin_sub_overflow(a.l[0], b.l[0], &r.l[0]);
  r.l[1] = a.l[1] - b.l[1] - c;
  return r;
}

// a + b or a - b without a data-dependent branch
static inline u256 add_signed_256(u256 a, u256 b, int negative) {
  u128 mask = -(u128)negative;
  u256 nb = {{b.l[0] ^ mask, b.l[1] ^ mask}}, one = {{(u128)negative, 0}};
  return add_256(a, add_256(nb, one));
}

// f << shift in the 256-bit frame, for shift < 128
static inline u256 place_256(u128 f, unsigned shift) {
  u256 r = {{f << shift, (f >> 1) >> (127 - shift)}};
  return r;
}

// the top 128 bits of s << shift, for shift < 64
static inline u128 top_256(u256 s, unsigned shift) {
  return (s.l[1] << shift) | ((s.l[0] >> 1) >> (127 - shift));
}

// x >> shift with the bit below it folded into the last bit, 0 < shift < 128
static inline u128 shr_round(u128 x, unsigned shift) {
  return (x >> shift) | ((x >> (shift - 1)) & 1);
}

static inline u384 add_384(u384 a, u384 b) {
  u384 r;
  int c0 = __builtin_add_overflow(a.l[0], b.l[0], &r.l[0]);
  int c1 = __builtin_add_overflow(a.l[1], b.l[1], &r.l[1]);
  int c2 = __builtin_add_overflow(r.l[1], (u128)c0, &r.l[1]);
  r.l[2] = a.l[2] + b.l[2] + c1 + c2;
  return r;
}

static inline u384 sub_384(u384 a, u384 b) {
  u384 r;
  int c0 = __builtin_sub_overflow(a.l[0], b.l[0], &r.l[0]);
  int c1 = __builtin_sub_overflow(a.l[1], b.l[1], &r.l[1]);
  int c2 = __builtin_sub_overflow(r.l[1], (u128)c0, &r.l[1]);
  r.l[2] = a.l[2] - b.l[2] - c1 - c2;
  return r;
}

// x << shift, discarding whatever leaves the window, for shift < 384
static inline u384 shl_384(u384 x, unsigned shift) {
  unsigned word = shift / 128, bits = shift % 128;
  u384 r = {{0, 0, 0}};
  for (unsigned i = word; i < 3; i++) {
    u128 carry = (bits == 0 || i == word) ? 0 : x.l[i - word - 1] >> (128 - bits);
    r.l[i] = (x.l[i - word] << bits) | carry;
  }
  return r;
}

// x >> shift, saturating to zero past the window
static inline u384 shr_384_sat(u384 x, unsigned shift) {
  u384 r = {{0, 0, 0}};
  if (shift >= 384) return r;
  unsigned word = shift / 128, bits = shift % 128;
  for (unsigned i = word; i < 3; i++) {
    u128 carry = (i + 1 < 3 && bits != 0) ? x.l[i + 1] << (128 - bits) : 0;
    r.l[i - word] = (x.l[i] >> bits) | carry;
  }
  return r;
}

// leading zeros of a 384-bit value, 384 when it is zero
static inline int lz_384(u384 x) {
  if (x.l[2]) return clz128(x.l[2]);
  if (x.l[1]) return 128 + clz128(x.l[1]);
  return 256 + clz128(x.l[0]);
}

/* high 384 bits of a 384x384-bit product: the dropped tail leaves it up to
   four units short of the exact value, never over */
static inline u384 mul_hi_384(u384 a, u384 b) {
  u128 h02, l02, h11, l11, h20, l20, h12, l12, h21, l21, h22, l22, sum, diagonal;
  wmul(a.l[0], b.l[2], &h02, &l02);
  wmul(a.l[1], b.l[1], &h11, &l11);
  wmul(a.l[2], b.l[0], &h20, &l20);
  wmul(a.l[1], b.l[2], &h12, &l12);
  wmul(a.l[2], b.l[1], &h21, &l21);
  wmul(a.l[2], b.l[2], &h22, &l22);
  /* The diagonal one limb below the window contributes its high halves plus
     the carry of its low halves; everything further down is the slack above. */
  int carry_low = __builtin_add_overflow(l02, l11, &sum);
  int carry_high = __builtin_add_overflow(sum, l20, &sum);
  int first = __builtin_add_overflow(h02, h11, &diagonal);
  int second = __builtin_add_overflow(diagonal, h20, &diagonal);
  int third = __builtin_add_overflow(diagonal, (u128)carry_low + carry_high, &diagonal);
  u384 t1 = {{l12, h12, 0}}, t2 = {{l21, h21, 0}}, t3 = {{0, l22, h22}};
  u384 t4 = {{diagonal, (u128)first + second + third, 0}};
  return add_384(add_384(t1, t2), add_384(t3, t4));
}

/* high 256 bits of a 256x256-bit product: the dropped tail leaves it up to
   one unit short of the exact value, never over */
static inline u256 mul_hi_256(u256 a, u256 b) {
  u128 high, low, cross_high, cross_low, other_high, other_low, sum, middle;
  wmul(a.l[1], b.l[1], &high, &low);
  wmul(a.l[1], b.l[0], &cross_high, &cross_low);
  wmul(a.l[0], b.l[1], &other_high, &other_low);
  /* The two cross terms and the top of a[0]*b[0] all land one limb below the
     window, so only their carry into it survives. */
  int carry = __builtin_add_overflow(cross_low, other_low, &sum);
  int tail_carry = __builtin_add_overflow(sum, mhi_approx(a.l[0], b.l[0]), &sum);
  int overflow = __builtin_add_overflow(cross_high, other_high, &middle);
  int spill = __builtin_add_overflow(middle, (u128)carry + tail_carry, &middle);
  int final_carry = __builtin_add_overflow(low, middle, &low);
  u256 r = {{low, high + overflow + spill + final_carry}};
  return r;
}

/* ---------- reduction ---------- */

/* m*win as W+3 little-endian 64-bit limbs, for a window win of W limbs most
   significant first: the product fills W+2 of them and the spare top limb
   stays zero so the funnels' last read is in range. */
static inline void product(u128 m, const u64 *win, int W, u64 *p) {
  u128 low = (u64)m, high = m >> 64, carry = 0;
  for (int c = 0; c < W + 3; c++) {
    u128 cur = c < W ? win[W - 1 - c] : 0;
    u128 prev = (c >= 1 && c <= W) ? win[W - c] : 0;
    /* high < 2^49 keeps the first sum under 2^114; only the second can
       spill, and its bit goes straight into the carry. */
    u128 acc = high * prev + carry, t;
    int spill = __builtin_add_overflow(acc, low * cur, &t);
    p[c] = (u64)t;
    carry = (t >> 64) | ((u128)spill << 64);
  }
}

/* The 2/pi window and the product's alignment for x = m*2^(e-112): bits of
   2/pi above position e-114 contribute multiples of 4 to x*2/pi, so the
   window starts at the limb holding bit e-113; within it, *shift says how
   far the units bit of x*2/pi sits below the product's bit 64*W-2 --
   negative below |x| = 2^114, where the window is the top of 2/pi. */
static inline const u64 *window(int e, int *shift) {
  int big = e - 114;
  if (big >= 0) {
    *shift = big % 64;
    return FRAC_2_PI + big / 64;
  }
  *shift = big;
  return FRAC_2_PI;
}

// the reduced angle theta = |g|*pi/2 as t1*2^(et-128), and its breakpoint
typedef struct {
  int n;        // round(256*x/pi) mod 512: quadrant n>>7, breakpoint n&127
  int negative; // g < 0: the angle sits below its breakpoint
  u128 t1;
  int et;
} residual;

/* Payne-Hanek on six limbs of 2/pi; 0 when the residual keeps fewer than
   136 of the fraction's 192 bits.  Five limbs would leave the tail of 2/pi
   below the window at 2^(shift-205) of the units bit, up to 2^-142, which
   the sine near a multiple of pi cannot afford; six put it under 2^-206. */
static inline int reduce(u128 m, int e, residual *r) {
  int shift;
  const u64 *win = window(e, &shift);
  u64 p[9];
  product(m, win, 6, p);
  /* The fraction is the 192 bits below the units bit, the quadrant the two
     above: four funnels at one offset, from limb i <= 4. */
  unsigned base = 190 - shift; // 127 <= base <= 312
  unsigned i = (base / 64) & 7, bits = base % 64;
  u64 f0 = funnel_down(p[i], p[i + 1], bits);
  u64 f1 = funnel_down(p[i + 1], p[i + 2], bits);
  u64 f2 = funnel_down(p[i + 2], p[i + 3], bits);
  u64 quadrant = funnel_down(p[i + 3], p[i + 4], bits) & 3;

  // n = round(256*x/pi); the residual's top limb becomes signed
  u128 top = ((u128)quadrant << 64) | f2;
  int n = (int)(((top + ((u128)1 << 56)) >> 57) & 511);
  f2 -= (u64)(n & 127) << 57;
  int negative = (i64)f2 < 0;
  u64 mask = -(u64)negative, g0, g1, g2;
  int c0 = __builtin_add_overflow(f0 ^ mask, (u64)negative, &g0);
  int c1 = __builtin_add_overflow(f1 ^ mask, (u64)c0, &g1);
  g2 = (f2 ^ mask) + c1;
  if (g2 == 0) return 0;
  int lz = __builtin_clzll(g2);
  if (lz > MAX_LZ) return 0;
  /* |g| <= 1/256 leaves at least seven leading zeros, so every shift below
     is in range; |g| = G*2^(-128-lz) for the top 128 bits G. */
  u64 high = (g2 << lz) | (g1 >> (64 - lz));
  u64 low = (g1 << lz) | (g0 >> (64 - lz));
  u128 g = ((u128)high << 64) | low, ph, pl;
  wmul(g, PIO2_128, &ph, &pl);
  int lzt = clz128(ph);
  u256 t = {{pl, ph}};
  r->n = n;
  r->negative = negative;
  r->t1 = top_256(t, lzt);
  r->et = 1 - (lz + lzt);
  return 1;
}

/* theta^2 rounded into a 2^-128 word (u), theta^4 likewise (v), and the
   unshifted theta^2 = u1*2^(2*et-128) the cosine's correction rides on */
static inline void squares(u128 t1, int et, u128 *u, u128 *v, u128 *u1) {
  *u1 = mhi_approx(t1, t1);
  *u = shr_round(*u1, (unsigned)(-2 * et));
  *v = mhi_approx(*u, *u);
}

/* sin(theta) in theta's own floating form: t1*(1 - u*(A - u*B)) with the
   even and odd halves of the degree-four minimax SIN_FAST in v.
   Its contribution to the ratio is below u*2^-114 < 2^-128.69. */
static inline u128 sin_frac(u128 t1, u128 u, u128 v) {
#define S(k) SIN_FAST[k]
  u128 a = S(0) + mhi_approx(v, S(2) + mhi_approx(v, S(4)));
  u128 b = S(1) + mhi_approx(v, S(3));
#undef S
  return t1 - mhi_approx(mhi_approx(t1, u), a - mhi_approx(u, b));
}

/* 1 - cos(theta) as the floating fraction c1*2^(2*et-128): theta^2*(1/2 -
   u*W) with W the even and odd halves of sum (-1)^k u^k/(2k+4)! in v. Six
   terms: the omitted seventh contributes less than 2^-139 to cos(theta). */
static inline u128 cos_corr(u128 u1, u128 u, u128 v) {
#define C(k) COS_COEF[k][2]
  u128 e = C(1) + mhi_approx(v, C(3) + mhi_approx(v, C(5)));
  u128 o = C(2) + mhi_approx(v, C(4));
  return mhi_approx(u1, C(0) - mhi_approx(u, e - mhi_approx(u, o)));
#undef C
}

/* The fast path: the magnitude as a floating 128-bit fraction frac*2^(e2-128)
   with the sign it contributes in *flip, or 0 when the reduction cannot
   vouch for it. */
static inline int fast(u128 m, int e, int cosine, u128 *frac, int *e2, u128 *flip) {
  u128 u, v, u1;
  if (e < DIRECT) {
    u128 t1 = m << 15;
    int et = e + 1;
    squares(t1, et, &u, &v, &u1);
    if (cosine) {
      u256 all = {{~(u128)0, ~(u128)0}};
      *frac = sub_256(all, place_256(cos_corr(u1, u, v), 2 * et + 128)).l[1];
      *e2 = 0;
    } else {
      // sin(theta) < theta drops a leading bit when t1 starts a binade
      u128 s1 = sin_frac(t1, u, v);
      int lz = clz128(s1);
      *frac = s1 << lz;
      *e2 = et - lz;
    }
    *flip = 0;
    return 1;
  }
  residual r;
  if (!reduce(m, e, &r)) return 0;
  squares(r.t1, r.et, &u, &v, &u1);
  u128 s1 = sin_frac(r.t1, u, v);
  /* The cosine is the sine a quadrant on; the top bit of the quadrant is the
     sign, the low bit which of sin A and cos A is wanted. */
  int k = (r.n >> 7) + cosine, want_cos = k & 1, j = r.n & 127;
  *flip = (k & 2) ? SIGN_MASK : 0;
  if (j == 0 && !want_cos) {
    int lz = clz128(s1);
    *flip ^= r.negative ? SIGN_MASK : 0;
    *frac = s1 << lz;
    *e2 = r.et - lz;
    return 1;
  }
  u128 c1 = cos_corr(u1, u, v);
  const u128 *first = SINCOS[j][want_cos], *second = SINCOS[j][!want_cos];
  u256 base = {{first[1], first[2]}};
  u256 c = place_256(mhi_approx(first[2], c1), 2 * r.et + 128);
  u256 s = place_256(mhi_approx(second[2], s1), r.et + 128);
  u256 f = add_signed_256(sub_256(base, c), s, r.negative != want_cos);
  int lz = clz128(f.l[1]);
  *frac = top_256(f, lz);
  *e2 = -lz;
  return 1;
}

/* Round the fast frame on its fixed 15-bit guard; 0 hands the window around
   the rounding boundary to the accurate path.  The result is never subnormal
   here: |x| >= 2^-57 keeps it above 2^-124. */
static inline int round_fast(u128 frac, int e2, u128 sign, unsigned rm, u128 *out) {
  unsigned rest = frac & GUARD_MASK;
  // the boundary is the midpoint in round-to-nearest, the grid point otherwise
  unsigned boundary = (rm == RM_NEAREST) << (GUARD - 1);
  if (((rest + ZIV_GATE - boundary) & GUARD_MASK) <= 2 * ZIV_GATE) return 0;
  /* The gate has already ruled out the boundary: the guard's top bit decides
     in round-to-nearest, and the discarded bits cannot flip it; a directed
     mode rounds the truncated frame by its direction alone. */
  int up = rm == RM_NEAREST ? rest > GUARD_HALF : round_away(rm, sign);
  *out = sign | (((u128)(e2 + 16382) << 112) + (frac >> GUARD) - IMPLICIT_BIT + up);
  return 1;
}

/* ---------- the 384-bit path ---------- */

// reduce() on ten limbs of 2/pi and a 448-bit fraction, the residual as a
// normalized 384-bit fraction t*2^(et-384)
static void reduce_wide(u128 m, int e, int *n, int *negative, u384 *t, int *et) {
  int shift;
  const u64 *win = window(e, &shift);
  u64 p[13];
  product(m, win, 10, p);
  unsigned base = 190 - shift; // 127 <= base <= 312
  unsigned i = (base / 64) & 7, bits = base % 64;
  u64 f[7];
  for (int k = 0; k < 7; k++) f[k] = funnel_down(p[i + k], p[i + k + 1], bits);
  u64 quadrant = funnel_down(p[i + 7], p[i + 8], bits) & 3;
  u128 top = ((u128)quadrant << 64) | f[6];
  int nn = (int)(((top + ((u128)1 << 56)) >> 57) & 511);
  f[6] -= (u64)(nn & 127) << 57;
  int neg = (i64)f[6] < 0;
  u64 mask = -(u64)neg;
  int carry = neg;
  for (int k = 0; k < 7; k++) carry = __builtin_add_overflow(f[k] ^ mask, (u64)carry, &f[k]);
  int lz = 448;
  for (int k = 6; k >= 0; k--)
    if (f[k]) { lz = 64 * (6 - k) + __builtin_clzll(f[k]); break; }
  /* No binary128 comes within 2^-124 of a multiple of pi/2, so the residual
     keeps over 300 of its 448 bits (lz < 140); ten limbs leave the tail of
     2/pi under 2^-462 of the units bit, so all 448 are meaningful. */
  unsigned word = lz / 64, wbits = lz % 64;
  u64 s[7] = {0, 0, 0, 0, 0, 0, 0};
  for (unsigned k = word; k < 7; k++) {
    u64 c = (wbits == 0 || k == word) ? 0 : f[k - word - 1] >> (64 - wbits);
    s[k] = (f[k - word] << wbits) | c;
  }
  u384 g = {{(u128)s[1] | (u128)s[2] << 64, (u128)s[3] | (u128)s[4] << 64, (u128)s[5] | (u128)s[6] << 64}};
  u384 pio2 = {{PIO2_384[0], PIO2_384[1], PIO2_384[2]}};
  u384 tt = mul_hi_384(g, pio2);
  int lzt = clz128(tt.l[2]);
  *n = nn;
  *negative = neg;
  *t = shl_384(tt, lzt);
  *et = 1 - (lz + lzt);
}

/* sum_{k>=0} (-1)^k coef[k]*u^k, eighteen terms by Horner in three tiers:
   terms 11..17 at 128 bits, 2..10 at 256, 0..1 at 384.  Every step stays
   positive because u*coef[k+1] < coef[k].  Each tier's slack -- under 2^-126
   for the narrow one, 2^-253 for the middle -- rides u^11 < 2^-161 or
   u^2 < 2^-29 (u < 2^-14.68) into the sum, so the result is within 2^-282 of
   the exact value, and the caller's multiply by u puts that below 2^-296.
   Mirrors correction_384 in metallic-rs's atan2.rs. */
static u384 alternating(u384 u, const u128 coef[][3]) {
  u128 narrow = coef[17][2];
  for (int k = 16; k >= 11; k--)
    narrow = coef[k][2] - mhi_approx(u.l[2], narrow);
  u256 middle = {{0, narrow}}, u2 = {{u.l[1], u.l[2]}};
  for (int k = 10; k >= 2; k--) {
    u256 c = {{coef[k][1], coef[k][2]}};
    middle = sub_256(c, mul_hi_256(u2, middle));
  }
  u384 q = {{0, middle.l[0], middle.l[1]}};
  for (int k = 1; k >= 0; k--) {
    u384 c = {{coef[k][0], coef[k][1], coef[k][2]}};
    q = sub_384(c, mul_hi_384(u, q));
  }
  return q;
}

/* Round a normalized 384-bit fraction frac*2^(e2-384) to binary128 in the
   current mode.  The result is never subnormal here (see round_fast). */
static inline u128 round_384(u384 frac, int e2, u128 sign, unsigned rm) {
  u128 mantissa = frac.l[2] >> GUARD;
  int round_bit = (frac.l[2] >> (GUARD - 1)) & 1;
  int sticky = ((frac.l[2] & (GUARD_MASK >> 1)) | frac.l[1] | frac.l[0]) != 0;
  int up = rm == RM_NEAREST ? round_bit && (sticky || (mantissa & 1))
                            : round_away(rm, sign) && (round_bit || sticky);
  return sign | (((u128)(e2 + 16382) << 112) + (mantissa - IMPLICIT_BIT) + up);
}

// the 384-bit path: everything the fast path would not decide
static u128 __attribute__((noinline, cold)) accurate(u128 m, int e, int cosine, u128 sign, unsigned rm) {
  int n, negative, et;
  u384 t;
  if (e < DIRECT) {
    n = 0;
    negative = 0;
    t.l[0] = 0;
    t.l[1] = 0;
    t.l[2] = m << 15;
    et = e + 1;
  } else
    reduce_wide(m, e, &n, &negative, &t, &et);
  u384 u = shr_384_sat(mul_hi_384(t, t), (unsigned)(-2 * et));
  int k = (n >> 7) + cosine, want_cos = k & 1, j = n & 127;
  sign ^= (k & 2) ? SIGN_MASK : 0;

  // sin(theta) = theta*(1 - u*Q) keeps theta's floating form, at most one bit short
  u384 s = sub_384(t, mul_hi_384(t, mul_hi_384(u, alternating(u, SIN_COEF))));
  int lzs = lz_384(s);
  s = shl_384(s, lzs);
  int es = et - lzs;
  if (j == 0 && !want_cos)
    return round_384(s, es, sign ^ (negative ? SIGN_MASK : 0), rm);

  // 1 - cos(theta) = u*Q, so T*cos(theta) = T - T*(u*Q) never overflows the frame
  u384 c = mul_hi_384(u, alternating(u, COS_COEF));
  u384 first = {{SINCOS[j][want_cos][0], SINCOS[j][want_cos][1], SINCOS[j][want_cos][2]}};
  u384 second = {{SINCOS[j][!want_cos][0], SINCOS[j][!want_cos][1], SINCOS[j][!want_cos][2]}};
  u384 base = sub_384(first, mul_hi_384(first, c));
  u384 term = shr_384_sat(mul_hi_384(second, s), (unsigned)(-es));
  u384 f = (negative != want_cos) ? sub_384(base, term) : add_384(base, term);
  int lz = lz_384(f);
  return round_384(shl_384(f, lz), -lz, sign, rm);
}

