static inline __float128 __attribute__((always_inline)) trig(__float128 x, int cosine) {
  unsigned rm, flags, oflags;
  FENV_GET(rm, flags);
  oflags = flags;
  u128 bits = asu128(x), ax = bits & ~SIGN_MASK, res;
  if (__builtin_expect(ax >= EXP_MASK, 0)) { // Inf or NaN
    if (ax == EXP_MASK) { // +-Inf: domain error
#ifdef CORE_MATH_SUPPORT_ERRNO
      errno = EDOM;
#endif
      flags |= FE_INVALID;
      FENV_RAISE(oflags, flags);
      return asf128(EXP_MASK | QUIET_BIT);
    }
    if (!(ax & QUIET_BIT)) { // signaling NaN
      flags |= FE_INVALID;
      FENV_RAISE(oflags, flags);
    }
    return asf128(bits | QUIET_BIT);
  }
  if (__builtin_expect(ax < TINY, 0)) {
    if (ax == 0) return cosine ? asf128(ONE) : x; // exact
    // sin(x) sits below x in magnitude and cos(x) below 1
    if (cosine)
      res = ONE - (rm != RM_NEAREST && !round_away(rm, 0));
    else {
      res = ax - (rm != RM_NEAREST && !round_away(rm, bits & SIGN_MASK));
      if (res < IMPLICIT_BIT) { // subnormal or zero after rounding
#ifdef CORE_MATH_SUPPORT_ERRNO
        errno = ERANGE;
#endif
        flags |= FE_UNDERFLOW;
      }
      res |= bits & SIGN_MASK;
    }
    flags |= FE_INEXACT;
    FENV_RAISE(oflags, flags);
    return asf128(res);
  }
  u128 m = (ax & MANTISSA_MASK) | IMPLICIT_BIT, sign = cosine ? 0 : bits & SIGN_MASK;
  int e = (int)(ax >> 112) - BIAS;
  u128 frac, flip;
  int e2;
  if (!(fast(m, e, cosine, &frac, &e2, &flip) && round_fast(frac, e2, sign ^ flip, rm, &res)))
    res = accurate(m, e, cosine, sign, rm);
  flags |= FE_INEXACT;
  FENV_RAISE(oflags, flags);
  return asf128(res);
}

__float128 cr_cosq(__float128 x) {
  return trig(x, 1);
}

