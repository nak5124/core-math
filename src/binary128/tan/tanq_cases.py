print('# Generated by tanq_cases.py; regression cases, not an exhaustive hard-case set.')
for s in ('0x0p+0', '0x1p-16494', '0x0.ffffffffffffffffffffffffffffp-16382',
          '0x1p-16382', '0x1.ffffffffffffffffffffffffffffp+16383', 'inf', 'nan'):
    emit(s)
for e in (-57, -8, -1, 0, 1, 112, 113, 114, 16383):
    neighbors(mp.ldexp(mp.mpf(1), e))
for j in range(1, 257):
    neighbors(mp.pi*j/256)     # table breakpoints, zeros, poles, tan=1
    neighbors(mp.pi*(2*j-1)/512)  # breakpoint selection seams
for e in range(0, 16384, 257):
    neighbors(mp.ldexp(mp.pi/2, e))
root = Path(__file__).resolve().parent.parent
print('# Deterministic subset of the inherited sine/cosine cancellation corpus.')
for name in ('sin/sinq.wc', 'cos/cosq.wc'):
    rows = [r for r in (root/name).read_text().splitlines() if r and not r.startswith('#')]
    for s in rows[::97]:
        emit(s)
