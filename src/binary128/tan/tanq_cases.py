#!/usr/bin/env python3
"""Reproduce tanq.wc: reduction seams, poles, binades and inherited inputs.

Run from any directory: python3 tanq_cases.py > tanq.wc
Requires mpmath. These are regression inputs, not a complete tangent
hard-to-round corpus. WORST_SYMMETRIC also tests their negatives.
"""
from pathlib import Path
from mpmath import mp
mp.prec = 17000
seen = set()

def emit(s):
    if s not in seen:
        seen.add(s)
        print(s)

def neighbors(x):
    f, e = mp.frexp(x)
    m = int(mp.nint(f * 2**113))
    for delta in (-2, -1, 0, 1, 2):
        k = m + delta
        # Unnormalized hexadecimal significands are exact C/strtoflt128 inputs.
        emit(f'0x{k:x}p{int(e)-113:+d}')

